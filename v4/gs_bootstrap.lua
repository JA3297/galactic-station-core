-- Galactic Station v4 unified bootstrap.
-- Run after OpenOS is installed on a writable HDD:
--   wget -f https://raw.githubusercontent.com/JA3297/galactic-station-core/main/v4/gs_bootstrap.lua /tmp/gs_bootstrap.lua
--   lua /tmp/gs_bootstrap.lua
--
-- Roles: GS-CORE-01, GS-CORE-02, GS-HUB-01, GS-LIFE-01.
-- The installer never formats disks. Replaced files are backed up.

local filesystem = require("filesystem")
local internet = require("internet")
local component = require("component")

local BASE = "https://raw.githubusercontent.com/JA3297/galactic-station-core/main/v4/"
local ROOT = "/etc/galactic"
local VERSION = "4.0.0"

local function trim(s)
  return tostring(s or ""):gsub("^%s+", ""):gsub("%s+$", "")
end

local function ask(prompt, default)
  io.write(prompt)
  if default then io.write(" [" .. default .. "]") end
  io.write(": ")
  local value = trim(io.read("*l"))
  if value == "" then return default end
  return value
end

local function yes(prompt, default)
  local d = default and "Y/n" or "y/N"
  local v = string.lower(ask(prompt .. " (" .. d .. ")", default and "y" or "n"))
  return v == "y" or v == "yes"
end

local function ensure(path)
  if not path or path == "" or path == "/" then return end
  local ok, why = filesystem.makeDirectory(path)
  if not ok and not filesystem.isDirectory(path) then
    error("Cannot create " .. path .. ": " .. tostring(why))
  end
end

local function backup(path)
  if not filesystem.exists(path) then return end
  local name = path .. ".pre-v4"
  local n = 1
  while filesystem.exists(name) do
    n = n + 1
    name = path .. ".pre-v4." .. tostring(n)
  end
  local ok, why = os.rename(path, name)
  if not ok then error("Cannot preserve " .. path .. ": " .. tostring(why)) end
end

local function writeFile(path, body)
  ensure(filesystem.path(path))
  local temp = path .. ".v4tmp"
  os.remove(temp)
  local f, why = io.open(temp, "wb")
  if not f then error("Cannot write " .. temp .. ": " .. tostring(why)) end
  f:write(body)
  f:close()
  backup(path)
  local ok, reason = os.rename(temp, path)
  if not ok then os.remove(temp); error("Cannot install " .. path .. ": " .. tostring(reason)) end
end

local function download(source)
  io.write("Downloading " .. source .. " ... ")
  local ok, handle = pcall(internet.request, BASE .. source)
  if not ok or not handle then error("HTTP request failed for " .. source .. ": " .. tostring(handle)) end
  local chunks = {}
  for chunk in handle do chunks[#chunks + 1] = chunk end
  local body = table.concat(chunks)
  if #body == 0 then error("Empty download: " .. source) end
  print("OK (" .. tostring(#body) .. " bytes)")
  return body
end

local function install(source, destination)
  writeFile(destination, download(source))
  print("Installed " .. destination)
end

local function hex(binary)
  return (binary:gsub(".", function(c) return string.format("%02x", c:byte()) end))
end

local function validHexKey(value)
  return type(value) == "string" and #value == 64 and not value:find("[^%x]")
end

local function provisionKey(isHub)
  ensure(ROOT)
  local keyPath = ROOT .. "/master.key"
  if filesystem.exists(keyPath) then
    local f = io.open(keyPath, "rb")
    local old = f and f:read("*a") or ""
    if f then f:close() end
    old = trim(old)
    if validHexKey(old) and yes("Keep existing station key", true) then
      return old
    end
  end

  if isHub then
    local dataAddress = component.list("data", true)()
    if not dataAddress then error("Tier 3 Data Card required to generate station key.") end
    local data = component.proxy(dataAddress)
    if type(data.random) ~= "function" then error("Data Card random() unavailable.") end
    local generated = hex(data.random(32))
    writeFile(keyPath, generated .. "\n")
    print("")
    print("NEW STATION KEY (64 HEX CHARACTERS). COPY PRIVATELY.")
    print(generated)
    print("Do not screenshot, publish, or send this key.")
    return generated
  end

  print("")
  print("Enter the 64-character key generated by GS-HUB-01.")
  local first = string.lower(ask("Station key"))
  local second = string.lower(ask("Confirm station key"))
  if first ~= second or not validHexKey(first) then
    error("Key confirmation failed. Expected exactly 64 hexadecimal characters.")
  end
  writeFile(keyPath, first .. "\n")
  return first
end

local function main()
  print("====================================================")
  print(" GALACTIC STATION v4 | UNIFIED INSTALLER")
  print("====================================================")
  print("Four maxed Tier 3 servers. No drive formatting.")
  print("")

  local roOK, readOnly = pcall(filesystem.isReadOnly, "/")
  if roOK and readOnly then
    error("Root filesystem is read-only. Install OpenOS to a writable hard drive first.")
  end

  print("Choose server role:")
  print("1 = GS-CORE-01 (primary operations)")
  print("2 = GS-CORE-02 (standby operations)")
  print("3 = GS-HUB-01 (witness, management, logs, GitHub)")
  print("4 = GS-LIFE-01 (Main Service equipment)")
  local choice = ask("Selection")
  local cfg

  if choice == "1" then
    cfg = {node_id="GS-CORE-01", role="core", side="primary", pair_id="GS-CORE-PAIR"}
  elseif choice == "2" then
    cfg = {node_id="GS-CORE-02", role="core", side="standby", pair_id="GS-CORE-PAIR"}
  elseif choice == "3" then
    cfg = {node_id="GS-HUB-01", role="hub", side="witness", pair_id="GS-CORE-PAIR"}
  elseif choice == "4" then
    cfg = {node_id="GS-LIFE-01", role="life_support", side="local", pair_id="NONE"}
  else
    error("Invalid selection.")
  end

  cfg.station_id = "GALACTIC-STATION"
  cfg.network_id = "GALACTIC-STATION-V4"
  cfg.manager_id = "GS-HUB-01"
  cfg.witness_id = "GS-HUB-01"
  cfg.protocol = 4

  local modemCount = 0
  for _ in component.list("modem", true) do modemCount = modemCount + 1 end
  if modemCount == 0 then error("Wired Network Card not detected as a modem component.") end
  local dataCount = 0
  local dataAddress
  for address in component.list("data", true) do
    dataCount = dataCount + 1
    if not dataAddress then dataAddress = address end
  end
  if dataCount == 0 then
    error("No component of type 'data' detected. Check that the Data Card is installed and connected to this server.")
  end

  local dataProxy = component.proxy(dataAddress)
  local requiredMethods = {"sha256", "encrypt", "decrypt", "random"}
  local missingMethods = {}
  for _, methodName in ipairs(requiredMethods) do
    if type(dataProxy[methodName]) ~= "function" then
      missingMethods[#missingMethods + 1] = methodName
    end
  end
  if #missingMethods > 0 then
    local reported = {}
    local methodsOK, methods = pcall(component.methods, dataAddress)
    if methodsOK and type(methods) == "table" then
      for methodName, present in pairs(methods) do
        if present then reported[#reported + 1] = tostring(methodName) end
      end
      table.sort(reported)
    end
    error("Data component detected at " .. tostring(dataAddress) ..
      " but Tier 2+ cryptography methods are missing: " .. table.concat(missingMethods, ", ") ..
      ". Reported methods: " .. table.concat(reported, ", ") ..
      ". A v4 server requires a Data Card exposing sha256, encrypt, decrypt and random.")
  end

  local randomOK, randomBytes = pcall(dataProxy.random, 16)
  if not randomOK or type(randomBytes) ~= "string" or #randomBytes ~= 16 then
    error("Data Card random(16) self-check failed: " .. tostring(randomBytes))
  end

  ensure(ROOT)
  ensure("/etc/rc.d")
  ensure("/usr/bin")
  ensure("/usr/lib")
  ensure("/var/galactic")
  ensure("/var/galactic/logs")
  ensure("/var/galactic/state")

  local key = provisionKey(choice == "3")
  local configText = "return {\n" ..
    "  station_id = " .. string.format("%q", cfg.station_id) .. ",\n" ..
    "  network_id = " .. string.format("%q", cfg.network_id) .. ",\n" ..
    "  node_id = " .. string.format("%q", cfg.node_id) .. ",\n" ..
    "  role = " .. string.format("%q", cfg.role) .. ",\n" ..
    "  side = " .. string.format("%q", cfg.side) .. ",\n" ..
    "  pair_id = " .. string.format("%q", cfg.pair_id) .. ",\n" ..
    "  manager_id = " .. string.format("%q", cfg.manager_id) .. ",\n" ..
    "  witness_id = " .. string.format("%q", cfg.witness_id) .. ",\n" ..
    "  protocol = 4\n}\n"
  writeFile(ROOT .. "/config.lua", configText)

  install("data_card_check.lua", "/usr/bin/data_card_check.lua")
  install("gs_crypto.lua", "/usr/lib/gs_crypto.lua")
  install("gs_life.lua", "/usr/lib/gs_life.lua")
  install("gsd.lua", "/usr/bin/gsd.lua")
  install("gs_rc.lua", "/etc/rc.d/gs.lua")

  if cfg.role == "hub" then
    install("gs.lua", "/usr/bin/gs.lua")
    install("gs_crypto_test.lua", "/usr/bin/gs_crypto_test.lua")
    install("gs_manifest.lua", "/usr/lib/gs_manifest.lua")
  end

  print("")
  print("====================================================")
  print(" INSTALLATION COMPLETE")
  print("Node: " .. cfg.node_id)
  print("Role: " .. cfg.role)
  print("Network: " .. cfg.network_id)
  print("====================================================")
  if cfg.role == "hub" then
    print("Run: lua /usr/bin/gs_crypto_test.lua")
    print("Start daemon: rc gs start")
    print("Enable at boot: rc gs enable")
    print("Launch console: lua /usr/bin/gs.lua")
  else
    print("Start daemon: rc gs start")
    print("Enable at boot: rc gs enable")
  end
  if cfg.role == "core" and cfg.side == "primary" then
    print("This is the preferred active core.")
  elseif cfg.role == "core" then
    print("This core remains standby until GS-HUB-01 grants authority.")
  elseif cfg.role == "life_support" then
    print("Life support monitoring is READ ONLY in v4 initial release.")
  end
  print("The daemon is not started automatically by the installer.")
end

local ok, err = pcall(main)
if not ok then
  print("")
  print("INSTALLATION FAILED: " .. tostring(err))
  print("No disk was formatted.")
end
